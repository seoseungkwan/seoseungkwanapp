// TASK-21 REQ-3618: 이름 뒤 조사를 이름 마지막 글자의 받침으로 고른다(josa.ts, design.md 5-3 조사 규칙)
import { describe, expect, it } from 'vitest'
import { josa, type JosaPair } from './josa'

describe('AC-3618.1 josa: 받침으로 조사 고르기', () => {
  it.each<[string, JosaPair, string]>([
    // 받침 없음 → 는·가·로
    ['도수', '은/는', '는'],
    ['도수', '이/가', '가'],
    ['도수', '으로/로', '로'],
    ['크라이오', '은/는', '는'],
    ['크라이오', '으로/로', '로'],
    ['물리치료', '은/는', '는'],
    // 받침 있음 → 은·이·으로
    ['씨암', '은/는', '은'],
    ['씨암', '이/가', '이'],
    ['씨암', '으로/로', '으로'],
    ['핫팩', '으로/로', '으로'],
    ['수액', '은/는', '은'],
    // 받침 ㄹ → 은·이는 그대로, 으로/로는 '로'
    ['수술', '은/는', '은'],
    ['수술', '이/가', '이'],
    ['수술', '으로/로', '로'],
  ])('AC-3618.1: ‘%s’ + %s → %s', (word, pair, want) => {
    expect(josa(word, pair)).toBe(want)
  })

  it.each(['sono', 'SONO', 'CRYO3', '씨암(주사)', '', '  ', 'A1', '도수2'])(
    "AC-3618.1: 마지막 글자가 한글이 아니면(%j) '은(는)'·'이(가)'·'(으)로'",
    (word) => {
      expect(josa(word, '은/는')).toBe('은(는)')
      expect(josa(word, '이/가')).toBe('이(가)')
      expect(josa(word, '으로/로')).toBe('(으)로')
    },
  )

  it('AC-3618.1: 앞뒤 빈칸은 떼고 마지막 글자를 본다', () => {
    expect(josa(' 도수 ', '은/는')).toBe('는')
    expect(josa('수액 ', '으로/로')).toBe('으로')
  })

  it("AC-3618.1: 한글 낱자(자모)만 있는 끝 글자는 한글 음절이 아니라 '은(는)'이다", () => {
    expect(josa('ㄱ', '은/는')).toBe('은(는)')
    expect(josa('가', '은/는')).toBe('는')
    expect(josa('힣', '은/는')).toBe('은')
  })
})
