import { describe, expect, it } from 'vitest'
import { josa } from './josa'

// 조사 고르기(spec google-link design.md 2절 표 7). 끝 글자가 한글이면 받침으로(로/으로는 받침 없음·ㄹ 받침 → 로),
// 숫자면 읽는 소리로(0·1·3·6·7·8 받침, 1·7·8은 ㄹ), 그 밖 글자는 받침 없음으로. 낱말은 모두 지어낸 이름이다

describe('AC-8520.5 josa — 낱말 끝에 맞춘 조사', () => {
  it.each([
    // [낱말, 짝, 답]
    ['정호연', '이/가', '이'],
    ['이수', '이/가', '가'],
    ['체외충격', '을/를', '을'],
    ['체외', '을/를', '를'],
    ['민', '은/는', '은'],
    ['호', '은/는', '는'],
    ['정호연', '와/과', '과'],
    ['정예시', '와/과', '와'],
    ['변경', '로/으로', '으로'],
    ['취소', '로/으로', '로'],
  ] as const)('AC-8520.5: 한글 받침 — %s + %s → %s', (word, pair, want) => {
    expect(josa(word, pair)).toBe(want)
  })

  it('AC-8520.5: ㄹ 받침은 로/으로에서만 받침 없음처럼 로이고, 다른 짝은 받침 있음이다', () => {
    expect(josa('물리치료실', '로/으로')).toBe('로')
    expect(josa('서울', '로/으로')).toBe('로')
    expect(josa('물리치료실', '을/를')).toBe('을')
    expect(josa('서울', '와/과')).toBe('과')
    expect(josa('서울', '이/가')).toBe('이')
    expect(josa('서울', '은/는')).toBe('은')
  })

  it.each([
    // 0 영 · 1 일 · 2 이 · 3 삼 · 4 사 · 5 오 · 6 육 · 7 칠 · 8 팔 · 9 구
    ['0', '을', '으로'],
    ['1', '을', '로'],
    ['2', '를', '로'],
    ['3', '을', '으로'],
    ['4', '를', '로'],
    ['5', '를', '로'],
    ['6', '을', '으로'],
    ['7', '을', '로'],
    ['8', '을', '로'],
    ['9', '를', '로'],
  ] as const)('AC-8520.5: 숫자는 읽는 소리 — 끝 %s → 을/를 %s · 로/으로 %s', (digit, eul, ro) => {
    expect(josa(`10${digit}`, '을/를')).toBe(eul)
    expect(josa(`병원 ${digit}`, '로/으로')).toBe(ro)
  })

  it('AC-8520.5: 그 밖 글자(영문·기호)는 받침 없음이고, 끝 빈칸은 보지 않는다', () => {
    expect(josa('Clinic', '을/를')).toBe('를')
    expect(josa('Clinic', '와/과')).toBe('와')
    expect(josa('Clinic', '로/으로')).toBe('로')
    expect(josa('Clinic', '이/가')).toBe('가')
    expect(josa('Clinic', '은/는')).toBe('는')
    expect(josa('7345 한예제 도수 30분 (원)', '로/으로')).toBe('로')
    expect(josa('정호연  ', '이/가')).toBe('이')
    expect(josa('', '을/를')).toBe('를')
  })
})

// 2절 표 7의 틀 글마다 받침 있는 낱말·없는 낱말 둘씩. 틀 글은 notes-calendar 글자 그대로 적고 `{ }`만 바꾼다
describe('AC-8520.5 josa — 2절 표 7의 틀 글', () => {
  const j = josa

  it("AC-8520.5: '{표시}'{은/는} 시행자 표시에 없어요", () => {
    const t = (w: string) => `'${w}'${j(w, '은/는')} 시행자 표시에 없어요`
    expect(t('민')).toBe("'민'은 시행자 표시에 없어요")
    expect(t('호')).toBe("'호'는 시행자 표시에 없어요")
  })

  it("AC-8520.5: '{글}'{을/를} 종류로 알아보지 못했어요 (고르면 '{글}'{은/는} 메모로 남아요)", () => {
    const t = (w: string) => `'${w}'${j(w, '을/를')} 종류로 알아보지 못했어요 (고르면 '${w}'${j(w, '은/는')} 메모로 남아요)`
    expect(t('체외')).toBe("'체외'를 종류로 알아보지 못했어요 (고르면 '체외'는 메모로 남아요)")
    expect(t('체외충격')).toBe("'체외충격'을 종류로 알아보지 못했어요 (고르면 '체외충격'은 메모로 남아요)")
  })

  it("AC-8520.5: '{이름}'{을/를} 원장님·직원 목록에서 찾지 못했어요", () => {
    const t = (w: string) => `'${w}'${j(w, '을/를')} 원장님·직원 목록에서 찾지 못했어요`
    expect(t('최호')).toBe("'최호'를 원장님·직원 목록에서 찾지 못했어요")
    expect(t('김민')).toBe("'김민'을 원장님·직원 목록에서 찾지 못했어요")
  })

  it('AC-8520.5: {시행자}{과/와} {시행자}{이/가} 같은 색({색})이에요.', () => {
    const t = (a: string, b: string, c: string) => `${a}${j(a, '와/과')} ${b}${j(b, '이/가')} 같은 색(${c})이에요.`
    expect(t('(호) 정호연', '(원) 박지원', '라벤더')).toBe('(호) 정호연과 (원) 박지원이 같은 색(라벤더)이에요.')
    expect(t('(현) 이수', '(호) 정호', '라벤더')).toBe('(현) 이수와 (호) 정호가 같은 색(라벤더)이에요.')
  })

  it("AC-8520.5: 구글에서 이 색 일정은 모두 '{취소|변경}'{으로/로} 알아봐요. — 시안 '취소'으로는 '취소'로", () => {
    const t = (w: string) => `구글에서 이 색 일정은 모두 '${w}'${j(w, '로/으로')} 알아봐요.`
    expect(t('취소')).toBe("구글에서 이 색 일정은 모두 '취소'로 알아봐요.")
    expect(t('변경')).toBe("구글에서 이 색 일정은 모두 '변경'으로 알아봐요.")
  })

  it("AC-8520.5: '{캘린더}'{으로/로} 잇고 다음 →", () => {
    const t = (w: string) => `'${w}'${j(w, '로/으로')} 잇고 다음 →`
    expect(t('2026 양지바른정형외과')).toBe("'2026 양지바른정형외과'로 잇고 다음 →")
    expect(t('병원 예약')).toBe("'병원 예약'으로 잇고 다음 →")
  })

  it('AC-8520.5: {캘린더}{을/를} 골랐어요 · 아직 가져오지 않았어요', () => {
    const t = (w: string) => `${w}${j(w, '을/를')} 골랐어요 · 아직 가져오지 않았어요`
    expect(t('2026 양지바른정형외과')).toBe('2026 양지바른정형외과를 골랐어요 · 아직 가져오지 않았어요')
    expect(t('병원 예약')).toBe('병원 예약을 골랐어요 · 아직 가져오지 않았어요')
  })

  it('AC-8520.5: 구글 캘린더 {캘린더}{와/과} 이어짐', () => {
    const t = (w: string) => `구글 캘린더 ${w}${j(w, '와/과')} 이어짐`
    expect(t('2026 양지바른정형외과')).toBe('구글 캘린더 2026 양지바른정형외과와 이어짐')
    expect(t('병원 예약')).toBe('구글 캘린더 병원 예약과 이어짐')
  })

  it('AC-8520.5: {종류}{으로/로} 봐요', () => {
    const t = (w: string) => `${w}${j(w, '로/으로')} 봐요`
    expect(t('도수')).toBe('도수로 봐요')
    expect(t('충격')).toBe('충격으로 봐요')
  })

  it('AC-8520.5: (예약 시행자 ({표시}) {이름}{과/와} 이어져 있어요)', () => {
    const t = (mark: string, name: string) => `(예약 시행자 (${mark}) ${name}${j(name, '와/과')} 이어져 있어요)`
    expect(t('호', '정호연')).toBe('(예약 시행자 (호) 정호연과 이어져 있어요)')
    expect(t('현', '이수')).toBe('(예약 시행자 (현) 이수와 이어져 있어요)')
  })

  it('AC-8520.5: … 구글 제목이 {제목}{으로/로} 다시 적혀요.', () => {
    const t = (w: string) => `구글 제목이 ${w}${j(w, '로/으로')} 다시 적혀요.`
    expect(t('7345 한예제 도수 30분 (원) 1부위만 해 주세요')).toBe('구글 제목이 7345 한예제 도수 30분 (원) 1부위만 해 주세요로 다시 적혀요.')
    expect(t('1234 홍길동 도수 30분 (호) 왼쪽')).toBe('구글 제목이 1234 홍길동 도수 30분 (호) 왼쪽으로 다시 적혀요.')
  })

  it('AC-8520.5: 시행자 글이 없어요. {종류}{은/는} 그때그때 하는 사람이 달라 색으로는 몰라요', () => {
    const t = (w: string) => `시행자 글이 없어요. ${w}${j(w, '은/는')} 그때그때 하는 사람이 달라 색으로는 몰라요`
    expect(t('충격파')).toBe('시행자 글이 없어요. 충격파는 그때그때 하는 사람이 달라 색으로는 몰라요')
    expect(t('체외충격')).toBe('시행자 글이 없어요. 체외충격은 그때그때 하는 사람이 달라 색으로는 몰라요')
  })
})
