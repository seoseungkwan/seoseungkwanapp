import { describe, expect, it } from 'vitest'
import { toRegion } from './region'

describe('AC-003.3 toRegion — 시·도 + 시·군·구 + 동·읍·면·가·리까지', () => {
  it.each([
    // step 4 시험 표
    ['서울특별시 강남구 역삼동 123-4', '서울특별시 강남구 역삼동'],
    ['서울특별시 강남구 테헤란로 123', '서울특별시 강남구'], // 도로명은 구까지
    ['경기도 성남시 분당구 정자동 12', '경기도 성남시 분당구 정자동'], // 시 안의 구
    ['경기도 화성시 봉담읍 와우리 45', '경기도 화성시 봉담읍 와우리'], // 읍 + 리
    ['서울특별시 중구 을지로3가 5', '서울특별시 중구 을지로3가'],
    // 가짜 파일의 나머지 주소
    ['서울특별시 서초구 강남대로 123', '서울특별시 서초구'],
    ['경기도 수원시 영통구 매탄동 12', '경기도 수원시 영통구 매탄동'],
    ['경기도 양평군 양평읍 양근리 45', '경기도 양평군 양평읍 양근리'],
    // 줄임말 시·도
    ['서울 강남구 역삼동 123-4', '서울 강남구 역삼동'],
    ['경기 성남시 분당구 정자동 12', '경기 성남시 분당구 정자동'],
    // 시·군·구가 없는 시
    ['세종특별자치시 조치원읍 원리 12', '세종특별자치시 조치원읍 원리'],
    ['세종특별자치시 한누리대로 123', '세종특별자치시'],
    // 길·면
    ['서울특별시 서초구 강남대로21길 5', '서울특별시 서초구'],
    ['강원특별자치도 홍천군 서면 팔봉리 7', '강원특별자치도 홍천군 서면 팔봉리'],
    // 숫자가 든 동 이름
    ['서울특별시 강남구 역삼1동 12', '서울특별시 강남구 역삼1동'],
  ])('%j → %j', (address, region) => {
    expect(toRegion(address)).toBe(region)
  })

  it('번지·건물·동호수·괄호 안 글은 버린다', () => {
    expect(toRegion('서울특별시 강남구 역삼동 123-4 가짜빌딩 101동 1001호')).toBe('서울특별시 강남구 역삼동')
    expect(toRegion('서울특별시 강남구 역삼동 123번지')).toBe('서울특별시 강남구 역삼동')
    expect(toRegion('서울특별시 강남구 역삼동, 가짜아파트 101동')).toBe('서울특별시 강남구 역삼동')
    // 도로명 뒤 괄호 안 동 이름은 꺼내지 않는다(도로명은 구까지)
    expect(toRegion('서울특별시 강남구 테헤란로 123, 4층 (역삼동, 가짜빌딩)')).toBe('서울특별시 강남구')
  })

  it('공백이 여러 칸이거나 앞뒤에 있어도 한 칸으로', () => {
    expect(toRegion('  서울특별시   강남구\t역삼동  123-4 ')).toBe('서울특별시 강남구 역삼동')
  })

  it('시·도 없이 시작해도 앞에서부터 자른다', () => {
    expect(toRegion('강남구 역삼동 123-4')).toBe('강남구 역삼동')
  })

  it.each(['', '   ', null, undefined])('빈 값 %j → null', (address) => {
    expect(toRegion(address)).toBeNull()
  })

  it.each(['123-4', '101동 1001호', '가짜빌딩 3층', '해외'])('행정 구역으로 시작하지 않으면 null: %j', (address) => {
    expect(toRegion(address)).toBeNull()
  })

  it('어떤 결과에도 숫자 번지가 남지 않는다', () => {
    const addresses = [
      '서울특별시 강남구 역삼동 123-4',
      '서울특별시 강남구 테헤란로 123',
      '경기도 성남시 분당구 정자동 12',
      '경기도 화성시 봉담읍 와우리 45',
      '서울특별시 중구 을지로3가 5',
      '서울특별시 강남구 역삼동 123번지 101동 1001호',
      '서울특별시 강남구 101동 1001호',
    ]
    for (const address of addresses) {
      expect(toRegion(address) ?? '').not.toMatch(/(^|\s)\d|\d+-\d+/)
    }
  })
})
