describe('AC-6107.1 HOLIDAYS', () => {
  it('AC-6107.1: 모든 값이 YYYY-MM-DD 날짜이고 겹침 없이 날짜 차례다', () => {
    expect(HOLIDAYS.length).toBeGreaterThan(0)
    for (const day of HOLIDAYS) expect(isYmd(day), day).toBe(true)
    expect(new Set(HOLIDAYS).size).toBe(HOLIDAYS.length)
    expect([...HOLIDAYS].sort()).toEqual([...HOLIDAYS])
  })

  it('AC-6107.1: 2025~2027년 것만 들어 있다', () => {
    expect(new Set(HOLIDAYS.map((day) => day.slice(0, 4)))).toEqual(new Set(['2025', '2026', '2027']))
  })

  it.each(Object.keys(EXPECTED))('AC-6107.1: %s년 공휴일(대체공휴일·임시공휴일·선거일 포함)이 빠짐없이 그대로 있다', (year) => {
    expect(HOLIDAYS.filter((day) => day.startsWith(year))).toEqual(EXPECTED[year])
  })

  it('AC-6107.1: 대체공휴일이 붙지 않는 날(토요일 현충일 다음 월요일·토요일 추석 다음 월요일)은 없다', () => {
    expect(HOLIDAYS).not.toContain('2026-06-08')
    expect(HOLIDAYS).not.toContain('2026-09-28')
  })
})
