export function errorInfo(code: ErrorCode): ErrorInfo {
  return ERRORS[code]
}

/** 이 파일에 문구가 있는 번호인가(도우미가 준 번호는 글자라 모르는 번호일 수 있다. 그때 화면은 번호만 보인다) */
export function isErrorCode(code: string): code is ErrorCode {
  return Object.hasOwn(ERRORS, code)
}
